/**
 * Generiert TypeScript-Typen aus dem Backend-OpenAPI-Schema.
 *
 * Lokaler Run-Voraussetzungen:
 * 1. Backend lokal hochgezogen: `cd ../backend && ./mvnw spring-boot:run`
 * 2. ENV gesetzt: `EXPO_PUBLIC_API_BASE_URL=http://localhost:8080` (oder via
 *    `.env`-File, das Expo automatisch lädt — hier wird der Wert direkt aus
 *    `process.env` gelesen).
 *
 * Dann:
 *   npm run generate:api
 *
 * Output landet in `lib/api/types.gen.ts` und überschreibt den Fallback-
 * Handcode aus FE-S1 Sub-A.
 */
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, '..');
const OUT_PATH = resolve(REPO_ROOT, 'lib/api/types.gen.ts');

const baseUrl = (process.env.EXPO_PUBLIC_API_BASE_URL ?? 'http://localhost:8080').replace(
  /\/+$/,
  '',
);
const docsUrl = `${baseUrl}/v3/api-docs`;

async function main(): Promise<void> {
  console.log(`[generate-api] fetching ${docsUrl}`);

  let res: Response;
  try {
    res = await fetch(docsUrl);
  } catch (err) {
    console.error(
      `[generate-api] failed to reach ${docsUrl}. ` +
        `Ist das Backend lokal hochgezogen? (cd ../backend && ./mvnw spring-boot:run)`,
    );
    console.error(err);
    process.exit(1);
  }

  if (!res.ok) {
    console.error(
      `[generate-api] ${docsUrl} antwortete ${res.status} ${res.statusText}.`,
    );
    process.exit(1);
  }

  let schema: unknown;
  try {
    schema = await res.json();
  } catch (err) {
    console.error(`[generate-api] Antwort von ${docsUrl} ist kein gültiges JSON.`);
    console.error(err);
    process.exit(1);
  }

  const ast = await openapiTS(schema as Parameters<typeof openapiTS>[0]);
  const code = astToString(ast);

  const header =
    '// AUTO-GENERATED by scripts/generate-api.ts — DO NOT EDIT.\n' +
    `// Source: ${docsUrl}\n` +
    `// Run: npm run generate:api\n\n`;

  await writeFile(OUT_PATH, header + code, 'utf8');
  console.log(`[generate-api] wrote ${OUT_PATH}`);
}

main().catch((err) => {
  console.error('[generate-api] unerwarteter Fehler:');
  console.error(err);
  process.exit(1);
});
